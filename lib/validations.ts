import * as z from "zod";

// Shared between client-side (react-hook-free, plain <form>) and server
// action validation, so the rules can never drift between the two layers.

export const emailSchema = z.email({ error: "Enter a valid email address." }).trim();

export const passwordSchema = z
  .string()
  .min(8, { error: "Password must be at least 8 characters." })
  .max(72, { error: "Password is too long." });

export const loginSchema = z.object({
  email: emailSchema,
  password: z.string().min(1, { error: "Enter your password." }),
});
export type LoginInput = z.infer<typeof loginSchema>;

export const registerSchema = z.object({
  name: z
    .string()
    .trim()
    .min(2, { error: "Name must be at least 2 characters." })
    .max(100, { error: "Name is too long." }),
  email: emailSchema,
  password: passwordSchema,
});
export type RegisterInput = z.infer<typeof registerSchema>;

// `z.guid()`, not `z.uuid()`: zod v4's `uuid()` also enforces the RFC 4122
// version/variant bits, so perfectly valid Postgres uuids that weren't
// generated by gen_random_uuid() (e.g. hand-seeded ids like
// "aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa") were rejected as "invalid". The
// bookings foreign keys are what actually guarantee the row exists.
const uuidField = (label: string) => z.guid({ error: `Invalid ${label}.` });

export const bookingSchema = z.object({
  classId: uuidField("class selection"),
  trainerId: uuidField("trainer selection"),
  bookingDate: z
    .string()
    .min(1, { error: "Choose a date." })
    .refine(
      (value) => {
        const date = new Date(`${value}T00:00:00`);
        if (Number.isNaN(date.getTime())) return false;
        const today = new Date();
        today.setHours(0, 0, 0, 0);
        return date >= today;
      },
      { error: "The date must be today or later." }
    ),
  bookingTime: z
    .string()
    .regex(/^([01]\d|2[0-3]):([0-5]\d)$/, { error: "Enter a valid time (HH:MM)." }),
  note: z
    .string()
    .trim()
    .max(500, { error: "The message can be at most 500 characters." })
    .optional()
    .or(z.literal("")),
});
export type BookingInput = z.infer<typeof bookingSchema>;
